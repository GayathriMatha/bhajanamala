function cleanLine(s) {
  return s
    .replace(/[|॥।.,!?"'`[\](){}]+/g, ' ')
    .replace(/[\u200c\u200d]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function firstWords(line, n = 4) {
  return cleanLine(line).split(' ').filter(Boolean).slice(0, n).join(' ');
}

function pageText(page) {
  const file = path.join(textDir, `page-${page}.txt`);
  if (!fs.existsSync(file)) return '';
  return fs.readFileSync(file, 'utf8');
}

function lyricsFromPage(page, opening) {
  const text = pageText(page);
  if (!text) return opening || '';
  const lines = text
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l && l !== 'భజనమాల' && !/^\d+$/.test(l));
  const needle = cleanLine(opening || '').slice(0, 12);
  let start = 0;
  if (needle) {
    const idx = lines.findIndex((l) => cleanLine(l).includes(needle.slice(0, 8)));
    if (idx >= 0) start = idx;
  }
  return lines.slice(start, start + 16).join('\n') || opening || '';
}

function loadOcrExtras() {
  if (!fs.existsSync(textDir)) return [];
  const files = fs
    .readdirSync(textDir)
    .filter((f) => /^page-\d+\.txt$/.test(f))
    .sort((a, b) => parseInt(a.match(/\d+/)[0], 10) - parseInt(b.match(/\d+/)[0], 10));

  const extras = [];
  const seen = new Set(curated.map((c) => c.phrase4));

  for (const file of files) {
    const page = parseInt(file.match(/\d+/)[0], 10);
    const text = fs.readFileSync(path.join(textDir, file), 'utf8');
    const lines = text.split(/\r?\n/).map((l) => l.trim());

    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];
      const prev = (lines[i - 1] || '').trim();
      if (!line || line === 'భజనమాల') continue;
      if (/^\(?\d{1,2}-\d{1,2}-\d{4}/.test(line)) continue;
      if (!/^\d{1,3}$/.test(prev)) continue;
      if (!/[అ-౿]/.test(line) || line.length < 10) continue;

      const phrase4 = firstWords(line, 4);
      const phrase3 = firstWords(line, 3);
      if (!phrase4 || seen.has(phrase4)) continue;
      if (/^(సీ|శా|ఉ|చం|శ్రే|శో|క|గే)\s*$/.test(phrase3)) continue;
      if (phrase4.length < 8) continue;

      seen.add(phrase4);
      const opening = firstWords(line, 14);
      extras.push({
        section: 'OCR',
        phrase3,
        phrase4,
        opening,
        page,
        lyrics: lyricsFromPage(page, opening),
        source: 'ocr',
      });
    }
  }
  return extras;
}

const extras = loadOcrExtras();
const songs = [
  ...curated.map((s) => ({ ...s, source: 'curated' })),
  ...extras.map((s, i) => ({ ...s, id: curated.length + i + 1 })),
];

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(
  outPath,
  JSON.stringify(
    {
      title: 'భజనమాల',
      subtitle: 'వాయిస్‌తో పాట వెతికి తెరవండి',
      total: songs.length,
      songs,
    },
    null,
    2
  ),
  'utf8'
);

