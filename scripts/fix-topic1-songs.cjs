const byId = new Map(data.songs.map((s) => [s.id, s]));

for (const f of fixed) {
  const old = byId.get(f.id) || {};
  let lyrics = old.lyrics || "";

  if (f.id === 3) {
    const a = byId.get(3)?.lyrics || "";
    const b = byId.get(4)?.lyrics || "";
    const cont = b.split("\u0c15. \u0c17\u0c41\u0c30\u0c41")[0] || "";
    lyrics = (a + "\n" + cont).trim();
  }

  if (f.id === 4) {
    const l = byId.get(4)?.lyrics || "";
    const idx = l.indexOf("\u0c15. \u0c17\u0c41\u0c30\u0c41");
    lyrics = idx >= 0 ? l.slice(idx).trim() : f.opening;
  }

  if (f.id === 6) {
    lyrics = (byId.get(7)?.lyrics || f.opening).trim();
  }

  if (f.id === 7) {
    const l8 = byId.get(8)?.lyrics || "";
    const parts = l8.split("\u0c2e\u0c3e\u0c23\u0c3f\u0c15\u0c4d\u0c2f\u0c35\u0c40\u0c23\u0c3e");
    lyrics = (parts[0] || "")
      .replace(/^[\u0c36\u0c4d\u0c30\u0c47\s]+/, "")
      .trim();
    if (!lyrics) lyrics = f.opening;
  }

  if (f.id === 8) {
    const l8 = byId.get(8)?.lyrics || "";
    const marker = "\u0c2e\u0c3e\u0c23\u0c3f\u0c15\u0c4d\u0c2f\u0c35\u0c40\u0c23\u0c3e";
    const idx = l8.indexOf(marker);
    lyrics = idx >= 0 ? l8.slice(idx).trim() : l8 || f.opening;
  }

  byId.set(f.id, {
    ...old,
    ...f,
    lyrics,
    source: "pdf-layout",
  });
}

data.songs = data.songs.map((s) => byId.get(s.id) || s);
fs.writeFileSync(path, JSON.stringify(data, null, 2), "utf8");

